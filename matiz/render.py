# Browsers get a lighter touch than editors and file managers, as in HyprDots
BROWSERS = "^(firefox|google-chrome|Google-chrome|brave-browser|Brave-browser|chromium)$"
APPS = ("^(code|Code|code-url-handler|thunar|Thunar|com.system76.CosmicFiles|"
        "com.system76.CosmicEdit|nwg-look|qt5ct|qt6ct|obsidian|org.gnome.Nautilus)$")
