def rofi_launcher(settings, current_text):
    c, launcher = colors(settings), settings["launcher"]
    text = re.sub(r"(columns:\s*)\d+;", rf"\g<1>{launcher['columns']};", current_text)
    text = re.sub(r"(lines:\s*)\d+;", rf"\g<1>{launcher['rows']};", text)
    # literal accent colors in the launcher (window border, selected element border)
    text = re.sub(r"(border-color:\s*)#[0-9a-fA-F]{6}55;", rf"\g<1>{with_alpha(c['accent'], 85 / 255)};", text)
    text = re.sub(r"(border-color:\s*)#[0-9a-fA-F]{6}aa;", rf"\g<1>{with_alpha(c['accent'], 170 / 255)};", text)
    text = re.sub(r"(text-color:\s*)#[0-9a-fA-F]{6}ff;", rf"\g<1>{with_alpha(c['bg'], 1)};", text)
    return text


def fuzzel(settings, current_text):
    c = colors(settings)
    values = {
        "background": with_alpha(c["bg"], settings["launcher"]["opacity"]).lstrip("#"),
        "text": with_alpha(c["fg"], 1).lstrip("#"),
        "match": with_alpha(c["accent"], 1).lstrip("#"),
        "selection": with_alpha(c["accent"], 0.2).lstrip("#"),
        "selection-text": with_alpha(c["accent"], 1).lstrip("#"),
        "selection-match": with_alpha(c["yellow"], 1).lstrip("#"),
        "border": with_alpha(c['accent'], 85 / 255).lstrip("#"),
    }
    out, section = [], None
    for line in current_text.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            section = stripped
        elif section == "[colors]" and "=" in stripped:
            key = stripped.split("=", 1)[0]
            if key in values:
                line = f"{key}={values[key]}"
        out.append(line)
    return "\n".join(out) + "\n"


