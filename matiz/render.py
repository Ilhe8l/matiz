def waybar_config(settings, current_text):
    """Updates position and height in config.jsonc, keeping its leading comment line."""
    lines = current_text.splitlines(keepends=True)
    comment = "".join(l for l in lines if l.lstrip().startswith("//"))
    body = "".join(l for l in lines if not l.lstrip().startswith("//"))
    data = json.loads(body)
    data["position"] = settings["bar"]["position"]
    data["height"] = settings["bar"]["height"]
    return comment + json.dumps(data, indent=4, ensure_ascii=False) + "\n"


