def kitty(settings):
    c = colors(settings)
    lines = [f"# {HEADER}",
             f"foreground {c['fg']}",
             f"background {c['bg_alt']}",
             f"background_opacity {settings['terminal']['opacity']:g}",
             f"selection_foreground {c['bg_alt']}",
             f"selection_background {c['accent']}",
             f"cursor {c['accent']}",
             f"cursor_text_color {c['bg_alt']}",
             f"url_color {c['accent2']}",
             f"active_border_color {c['accent']}",
             f"inactive_border_color {c['border']}",
             f"active_tab_background {c['accent']}",
             f"active_tab_foreground {c['bg']}",
             f"inactive_tab_background {c['surface']}",
             f"inactive_tab_foreground {c['fg_dim']}",
             f"tab_bar_background {c['bg']}"]
    lines += [f"color{i} {c[role]}" for i, role in enumerate(KITTY_SLOTS)]
    return "\n".join(lines) + "\n"


def qt_palette(settings):
    c = colors(settings)
    roles = [c["fg"], c["surface"], c["border"], c["surface"], c["bg"], c["bg_alt"],
             c["fg"], "#ffffff", c["fg"], c["bg"], c["bg_alt"], "#000000",
             c["accent"], c["bg"], c["accent2"], c["purple"], c["surface"],
             c["bg"], c["bg"], c["fg"], c["fg_dim"]]
    disabled = list(roles)
    for i in (0, 6, 8, 13, 20):
        disabled[i] = c["fg_dim"]
    disabled[12] = c["border"]
    return (f"# {HEADER}\n[ColorScheme]\n"
            f"active_colors={', '.join(roles)}\n"
            f"disabled_colors={', '.join(disabled)}\n"
            f"inactive_colors={', '.join(roles)}\n")


